<?php
/**
 * 本站与掲載校の関係についての開示。
 *
 * ------------------------------------------------------------------
 * なぜこのパーツが必要か（削除・改変する前に必ず読むこと）
 * ------------------------------------------------------------------
 * 当サイトの運営者は、掲載している学校の代理店ではない。
 * 学校から募集の委託を受けておらず、代理権もない。実務上行っているのは
 * 「出願書類の準備サポート」と「学校への取次ぎ」までであり、
 * 入学審査も学費の収受も学校と学生の間で直接行われる。
 *
 * にもかかわらず「提携校」「対応院校」といった表現を使うと、
 * 実在しない提携関係を示すことになり、景品表示法上の優良誤認表示に
 * 当たりうる。掲載校側から掲載差止めを求められる根拠にもなる。
 *
 * SEO 上もこの開示は損ではなく得になる。Google の品質評価ガイドラインは
 * YMYL 領域で「誰が、どういう立場でこの情報を出しているか」が
 * 明示されていることを評価する。関係性を曖昧にしたまま実在校の学費を
 * 載せているページより、立場を明記したページのほうが信頼性が高い。
 *
 * ------------------------------------------------------------------
 * 使い方
 * ------------------------------------------------------------------
 *   get_template_part( 'template-parts/relationship-disclosure', null, array(
 *       'variant' => 'full',   // full | compact
 *   ) );
 *
 *   full    …… 見出し付きの全文。学校情報を載せるページの本文末尾に置く。
 *   compact …… 1 行版。ページ冒頭やフッターなど、全文を置くと邪魔な場所に。
 *
 * @package StudyAbroadTheme
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$sa_variant = isset( $args['variant'] ) ? $args['variant'] : 'full';

if ( 'compact' === $sa_variant ) :
	?>
	<p class="sa-disclosure sa-disclosure--compact">
		<?php esc_html_e( '当サイトは掲載校の代理店ではありません。掲載情報は各校の公表資料に基づく参考情報です。', 'sa-theme' ); ?>
	</p>
	<?php
	return;
endif;
?>

<aside class="sa-disclosure sa-disclosure--full" aria-labelledby="sa-disclosure-title">
	<h2 class="sa-disclosure__title" id="sa-disclosure-title">
		<?php esc_html_e( '当サイトと掲載校の関係について', 'sa-theme' ); ?>
	</h2>
	<ul class="sa-disclosure__list">
		<li><?php esc_html_e( '当サイトは、掲載している学校の代理店ではありません。学校から募集の委託を受けておらず、学校を代理する権限もありません。', 'sa-theme' ); ?></li>
		<li><?php esc_html_e( '当サイトが行うのは、出願書類の準備サポートと、学校への書類・基本情報のお取次ぎまでです。', 'sa-theme' ); ?></li>
		<li><?php esc_html_e( '入学審査および合否の判定は、各学校が行います。当サイトが合格を保証することはできません。', 'sa-theme' ); ?></li>
		<li><?php esc_html_e( '入学金・授業料などのお支払いは、学生ご本人と学校の間で直接お手続きいただきます。当サイトが学費をお預かりすることはありません。', 'sa-theme' ); ?></li>
		<li><?php esc_html_e( '掲載内容は各校の公表資料をもとに整理した参考情報です。募集要項・学費・出願条件は変更される場合があります。お申し込み前に、必ず学校公式サイトで最新情報をご確認ください。', 'sa-theme' ); ?></li>
	</ul>
</aside>
